/**
 * 8. ランキング取得 (/ranking)
 */
app.get('/ranking', (req, res) => {
  // レベル順（降順）にソートして上位を表示
  const sortedList = Object.values(rankings).sort((a, b) => b.level - a.level);

  if (sortedList.length === 0) {
    return res.send("ランキングデータがまだありません。");
  }

  let resultText = "【殿堂入りランキング】\n\n";
  sortedList.slice(0, 10).forEach((item, index) => {
    resultText += `${index + 1}位: ${item.name} (Lv.${item.level}) - [${item.label}]\n`;
  });

  res.send(resultText);
});

