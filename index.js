/**
 * 2. ランダムマッチング (/match)
 */
app.get('/match', (req, res) => {
  const username = req.query.username;

  if (!username) {
    return res.status(400).send("ユーザー名が必要です");
  }

  // すでに待機中のプレイヤーがいる場合、マッチ成立
  if (waitingPlayer && waitingPlayer.username !== username) {
    const roomName = `room_${Date.now()}`;
    const selectedTheme = getRandomTheme();

    // 部屋情報を初期化
    rooms[roomName] = {
      theme: selectedTheme,
      messages: [],
      hpData: {
        [waitingPlayer.username]: 2000,
        [username]: 2000
      },
      players: [waitingPlayer.username, username]
    };

    const matchResponse = `MATCHING_SUCCESS | Room: ${roomName} | ${selectedTheme}`;

    // 待機中だった相手にレスポンスを返す
    waitingPlayer.res.send(matchResponse);
    waitingPlayer = null;

    // 自分にレスポンスを返す
    return res.send(matchResponse);
  } else {
    // 待機プレイヤーがいないか自分自身の場合は、待機状態にセット
    waitingPlayer = { username, res };

    // クライアントがタイムアウトする前に待機キャンセル等のハンドリングが必要な場合の保険
    req.on('close', () => {
      if (waitingPlayer && waitingPlayer.username === username) {
        waitingPlayer = null;
      }
    });
  }
});

/**
 * 3. 部屋の状態・チャット・HP取得 (/get-messages)
 */
app.get('/get-messages', (req, res) => {
  const roomName = req.query.roomName;

  if (!roomName || !rooms[roomName]) {
    return res.status(404).json({ error: "部屋が存在しないか、終了しました" });
  }

  res.json({
    messages: rooms[roomName].messages,
    hpData: rooms[roomName].hpData
  });
});

/**
 * 4. メッセージ送信 & 相手へのダメージ(/send-message)
 */
app.post('/send-message', (req, res) => {
  const { roomName, sender, text, hp } = req.body;

  if (!roomName || !rooms[roomName]) {
    return res.status(404).json({ error: "部屋が見つかりません" });
  }

  const room = rooms[roomName];

  // メッセージを追加
  room.messages.push({ sender, text, time: Date.now() });

  // 送信者のHPを更新
  if (room.hpData[sender] !== undefined) {
    room.hpData[sender] = hp;
  } else {
    room.hpData[sender] = hp;
  }

  // 相手へ100ダメージを与える
  Object.keys(room.hpData).forEach(playerKey => {
    if (playerKey !== sender) {
      room.hpData[playerKey] = Math.max(0, room.hpData[playerKey] - 100);
    }
  });

  res.json({ status: 'ok', hpData: room.hpData });
});

/**
 * 5. 試合終了・退出の通知 (/game-over)
 */
app.post('/game-over', (req, res) => {
  const { roomName } = req.body;
  if (roomName && rooms[roomName]) {
    delete rooms[roomName]; // 部屋のデータを削除
  }
  res.json({ status: 'cleaned' });
});

